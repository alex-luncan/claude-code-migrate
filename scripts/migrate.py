#!/usr/bin/env python3
"""
OSmigration - prepare a project for moving between Windows and macOS.

Safety model:
  * The source project is NEVER modified. It is copied to a temp directory
    and every change is applied to that copy.
  * The result is an archive named <project>_to-transfer.zip written to the
    work directory (default: the current working directory).

Subcommands:
  stage    copy the project into a temp staging directory (skips regenerable dirs)
  scan     detect OS-specific content in a staged copy, write MIGRATION_REPORT.md
  convert  apply safe automatic fixes to the staged copy, update the report
  package  zip the staged copy into <workdir>/<project>_to-transfer.zip
  prepare  stage + scan + convert (stop here so a human/Claude can do manual edits)
  all      stage + scan + convert + package

Stdlib only. Works on Python 3.8+ on both Windows and macOS.
"""
import argparse
import datetime as _dt
import json
import os
import re
import shutil
import stat
import sys
import tempfile
import zipfile
from pathlib import Path

VERSION = "1.0.0"
STATE_FILE = ".osmigration-state.json"
REPORT_MD = "MIGRATION_REPORT.md"
EXTRAS_DIR = "_claude-global-extras"

# Directories that are regenerated by a package manager / build tool.
DEFAULT_EXCLUDE_DIRS = {
    "node_modules", ".venv", "venv", "__pycache__", ".pytest_cache", ".mypy_cache",
    ".ruff_cache", ".tox", "dist", "build", ".next", ".nuxt", ".turbo", ".cache",
    "target", "obj", ".gradle", "coverage", ".parcel-cache", ".svelte-kit", ".angular",
    "site-packages", ".eggs",
}
JUNK_FILES = {".DS_Store", "Thumbs.db", "desktop.ini", "ehthumbs.db"}
JUNK_PREFIXES = ("._",)          # AppleDouble resource forks
JUNK_DIRS = {"__MACOSX"}

BINARY_EXT = {
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".bmp", ".tif", ".tiff", ".svgz",
    ".pdf", ".zip", ".gz", ".tgz", ".bz2", ".xz", ".7z", ".rar", ".jar", ".war",
    ".exe", ".dll", ".so", ".dylib", ".pyc", ".pyo", ".class", ".o", ".a", ".lib",
    ".woff", ".woff2", ".ttf", ".otf", ".eot", ".mp3", ".mp4", ".mov", ".avi", ".wav",
    ".ogg", ".flac", ".db", ".sqlite", ".sqlite3", ".bin", ".dat", ".parquet", ".npy",
    ".npz", ".pkl", ".pickle", ".h5", ".hdf5", ".docx", ".xlsx", ".pptx", ".psd",
}
CRLF_ON_WINDOWS_EXT = {".bat", ".cmd", ".ps1"}

# Extensions we treat as "config/text worth scanning for paths".
SCAN_TEXT_EXT = {
    ".json", ".jsonc", ".json5", ".yaml", ".yml", ".toml", ".ini", ".cfg", ".conf",
    ".env", ".md", ".txt", ".sh", ".bash", ".zsh", ".ps1", ".bat", ".cmd", ".py",
    ".js", ".ts", ".mjs", ".cjs", ".jsx", ".tsx", ".xml", ".properties", ".mk",
    ".gradle", ".kts", ".rb", ".go", ".rs", ".cs", ".csproj", ".sln", ".props",
}

WIN_ABS_RE = re.compile(r'(?<![A-Za-z0-9])([A-Za-z]:(?:\\\\|\\|/)[^\s"\'<>|,;)\]]*)')
MAC_ABS_RE = re.compile(r'(?<![\w/.])(/(?:Users|home|opt/homebrew|usr/local|Volumes)/[^\s"\'<>|,;)\]]*)')
WIN_ENV_RE = re.compile(r'%[A-Za-z_][A-Za-z0-9_()]*%')
UNIX_ENV_RE = re.compile(r'\$\{?[A-Z_][A-Z0-9_]*\}?')

# Markers that indicate a command was written for the OTHER shell.
WIN_SHELL_MARKERS = [
    (re.compile(r'\bcmd(?:\.exe)?\s+/[cCkK]\b'), "cmd /c wrapper"),
    (re.compile(r'\bpowershell(?:\.exe)?\b|\bpwsh\b'), "PowerShell invocation"),
    (re.compile(r'(?<![\w$])set\s+[A-Za-z_]\w*='), "cmd-style 'set VAR=' env assignment"),
    (re.compile(r'\b(?:xcopy|robocopy|rmdir|rd|del|erase|findstr|attrib)\b(?=\s|$)'), "cmd-only command"),
    (re.compile(r'\bcopy\s+(?:/[yY]\s+)?[^\s]+\s+[^\s]+'), "cmd 'copy' command"),
    (WIN_ENV_RE, "%VAR% environment variable syntax"),
    (re.compile(r'\.\\|\\(?=[A-Za-z0-9_.-]+\\)'), "backslash path separators"),
    (re.compile(r'\.(?:exe|bat|cmd|ps1)\b'), "Windows executable/script reference"),
]
UNIX_SHELL_MARKERS = [
    (re.compile(r'(?<![\w-])export\s+[A-Za-z_]\w*='), "'export VAR=' env assignment"),
    (re.compile(r'(?<![\w-])[A-Z_][A-Z0-9_]*=\S+\s+\w'), "inline 'VAR=value command' env assignment"),
    (re.compile(r'\brm\s+-[rf]+\b'), "'rm -rf' (use rimraf or PowerShell equivalent)"),
    (re.compile(r'\b(?:chmod|chown|ln\s+-s|which|open|brew|sudo|xargs|sed\s+-i|grep\s+-r)\b'), "unix-only command"),
    (re.compile(r'(?<![\w$])\$\{?[A-Za-z_]\w*\}?'), "$VAR environment variable syntax"),
    (re.compile(r'#!/(?:usr/)?bin/'), "shebang (needs Git Bash / WSL on Windows)"),
    (re.compile(r'\bsource\s+\S+|\B\.\s+\S+\.sh\b'), "'source' a shell file"),
]
NPM_CMD_SHIMS = {"npx", "npm", "yarn", "pnpm", "tsc", "tsx", "ts-node", "node-gyp", "uvx"}
WINDOWS_RESERVED = {"CON", "PRN", "AUX", "NUL"} | {f"COM{i}" for i in range(1, 10)} | {f"LPT{i}" for i in range(1, 10)}
WINDOWS_ILLEGAL_CHARS = re.compile(r'[<>:"|?*\x00-\x1f]')


# --------------------------------------------------------------------------- helpers

def log(msg):
    print(msg, flush=True)


def is_probably_binary(path: Path) -> bool:
    if path.suffix.lower() in BINARY_EXT:
        return True
    try:
        with open(path, "rb") as f:
            chunk = f.read(8192)
    except OSError:
        return True
    return b"\x00" in chunk


def read_text(path: Path):
    try:
        return path.read_bytes().decode("utf-8")
    except (UnicodeDecodeError, OSError):
        try:
            return path.read_bytes().decode("latin-1")
        except OSError:
            return None


def rel(path: Path, root: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return str(path)


def has_shebang(path: Path) -> bool:
    try:
        with open(path, "rb") as f:
            return f.read(2) == b"#!"
    except OSError:
        return False


def load_json_loose(text: str):
    """Parse JSON, tolerating // and /* */ comments and trailing commas (jsonc)."""
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        stripped = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
        stripped = re.sub(r'^\s*//.*$', '', stripped, flags=re.M)
        stripped = re.sub(r',(\s*[}\]])', r'\1', stripped)
        return json.loads(stripped)


class Finding:
    def __init__(self, category, severity, file, detail, suggestion="", line=None):
        self.category = category      # e.g. "line-endings", "mcp", "hooks", "paths"
        self.severity = severity      # "fixed" | "manual" | "info"
        self.file = file
        self.line = line
        self.detail = detail
        self.suggestion = suggestion

    def to_dict(self):
        return self.__dict__.copy()


# --------------------------------------------------------------------------- state

def state_path(staged: Path) -> Path:
    return staged / STATE_FILE


def save_state(staged: Path, state: dict):
    state_path(staged).write_text(json.dumps(state, indent=2), encoding="utf-8")


def load_state(staged: Path) -> dict:
    p = state_path(staged)
    if not p.exists():
        sys.exit(f"ERROR: {staged} does not look like an OSmigration staging dir (missing {STATE_FILE}).")
    return json.loads(p.read_text(encoding="utf-8"))


# --------------------------------------------------------------------------- stage

def cmd_stage(args) -> Path:
    source = Path(args.source).expanduser().resolve()
    if not source.is_dir():
        sys.exit(f"ERROR: source is not a directory: {source}")
    project_name = args.name or source.name
    exclude = set(DEFAULT_EXCLUDE_DIRS) | set(args.exclude or [])
    exclude -= set(args.keep or [])
    if args.exclude_git:
        exclude.add(".git")

    staged_parent = Path(tempfile.mkdtemp(prefix="osmigration-"))
    staged = staged_parent / project_name
    log(f"Staging copy of {source}")
    log(f"  -> {staged}")
    log(f"  excluding dirs: {', '.join(sorted(exclude))}")

    findings = []
    symlinks = []
    skipped_dirs = []
    archive_suffix = "_to-transfer.zip"

    def ignore(dir_path, names):
        ignored = set()
        d = Path(dir_path)
        for n in names:
            p = d / n
            if p.is_dir() and not p.is_symlink() and (n in exclude or n in JUNK_DIRS):
                ignored.add(n)
                skipped_dirs.append(rel(p, source))
            elif n in JUNK_FILES or n.startswith(JUNK_PREFIXES):
                ignored.add(n)
            elif n.endswith(archive_suffix) or n == REPORT_MD or n == STATE_FILE:
                ignored.add(n)   # don't nest a previous migration inside this one
            if p.is_symlink():
                symlinks.append(rel(p, source))
        return ignored

    # mac->win: dereference symlinks (Windows needs admin rights to create them).
    # win->mac: keep them as symlinks.
    keep_symlinks = args.direction == "win2mac"
    shutil.copytree(source, staged, symlinks=keep_symlinks, ignore=ignore,
                    ignore_dangling_symlinks=True)

    for s in symlinks:
        if keep_symlinks:
            findings.append(Finding("symlinks", "info", s,
                                    "Symlink preserved in the copy.").to_dict())
        else:
            findings.append(Finding("symlinks", "fixed", s,
                                    "Symlink replaced by a copy of its target (Windows cannot create symlinks without elevated rights).",
                                    "If this was meant to stay a link, recreate it manually on Windows (mklink) or restructure.").to_dict())

    state = {
        "version": VERSION,
        "created": _dt.datetime.now().isoformat(timespec="seconds"),
        "source": str(source),
        "source_posix": (args.source_root or source.as_posix()).replace("\\", "/").rstrip("/"),
        "project_name": project_name,
        "direction": args.direction,
        "dest_root": args.dest_root,
        "staged": str(staged),
        "excluded_dirs": sorted(exclude),
        "skipped_dirs": sorted(set(skipped_dirs)),
        "findings": findings,
        "steps_done": ["stage"],
    }

    if args.include_global:
        collect_global_extras(staged, state)

    save_state(staged, state)
    log(f"Staged. {len(skipped_dirs)} regenerable dir(s) skipped.")
    log(f"STAGED_DIR={staged}")
    return staged


def collect_global_extras(staged: Path, state: dict):
    """Copy user-level Claude Code config that is NOT part of the repo but that the
    user probably wants on the other machine. Never copies credentials."""
    home = Path.home()
    claude_dir = home / ".claude"
    extras = staged / EXTRAS_DIR
    extras.mkdir(exist_ok=True)
    copied = []

    for name in ("CLAUDE.md", "settings.json"):
        src = claude_dir / name
        if src.is_file():
            shutil.copy2(src, extras / name)
            copied.append(name)
    for name in ("commands", "agents", "skills"):
        src = claude_dir / name
        if src.is_dir():
            shutil.copytree(src, extras / name, dirs_exist_ok=True)
            copied.append(name + "/")

    # MCP servers from ~/.claude.json (user scope + this project's local scope)
    global_cfg = home / ".claude.json"
    mcp_out = {}
    if global_cfg.is_file():
        try:
            cfg = load_json_loose(global_cfg.read_text(encoding="utf-8"))
            if cfg.get("mcpServers"):
                mcp_out["user_scope"] = cfg["mcpServers"]
            projects = cfg.get("projects") or {}
            for key, val in projects.items():
                try:
                    same = Path(key).resolve() == Path(state["source"]).resolve()
                except OSError:
                    same = False
                if same and isinstance(val, dict) and val.get("mcpServers"):
                    mcp_out["project_local_scope"] = val["mcpServers"]
        except Exception as e:  # noqa: BLE001
            state["findings"].append(Finding("global-extras", "info", "~/.claude.json",
                                             f"Could not parse: {e}").to_dict())
    if mcp_out:
        (extras / "mcp-servers.json").write_text(json.dumps(mcp_out, indent=2), encoding="utf-8")
        copied.append("mcp-servers.json")

    (extras / "README.md").write_text(
        "# Claude Code user-level extras\n\n"
        "These files live OUTSIDE the project on the source machine (in ~/.claude and ~/.claude.json)\n"
        "and are not part of the repository. They are included so you can restore them on the target.\n\n"
        "**Nothing here should be copied blindly.** Review each file for absolute paths and shell syntax\n"
        "(the migration scan/convert has already run over this folder too, see MIGRATION_REPORT.md).\n\n"
        "| File | Restore to | Notes |\n|---|---|---|\n"
        "| CLAUDE.md | ~/.claude/CLAUDE.md | global instructions |\n"
        "| settings.json | ~/.claude/settings.json | user-level permissions/hooks; merge, do not overwrite |\n"
        "| commands/ | ~/.claude/commands/ | custom slash commands |\n"
        "| agents/ | ~/.claude/agents/ | custom subagents |\n"
        "| skills/ | ~/.claude/skills/ | user skills |\n"
        "| mcp-servers.json | re-add with `claude mcp add-json <name> '<json>' -s user` | one entry per server |\n\n"
        "Credentials are intentionally NOT included. Run `claude` and log in again on the target machine.\n",
        encoding="utf-8")
    state["global_extras"] = copied
    log(f"Collected user-level Claude extras: {', '.join(copied) or 'none found'}")


# --------------------------------------------------------------------------- scan

def iter_files(staged: Path):
    for root, dirs, files in os.walk(staged):
        r = Path(root)
        # never touch git internals
        dirs[:] = [d for d in dirs if not (r.name == staged.name and d == ".git" and r == staged)]
        if ".git" in r.parts:
            continue
        for f in files:
            p = r / f
            if f in (STATE_FILE, REPORT_MD) and r == staged:
                continue
            if p.is_symlink():
                continue
            yield p


def scan_command_string(cmd: str, direction: str):
    """Return list of (marker description) that indicate the command is written for the source OS."""
    markers = WIN_SHELL_MARKERS if direction == "win2mac" else UNIX_SHELL_MARKERS
    hits = []
    for rx, desc in markers:
        if rx.search(cmd):
            hits.append(desc)
    return hits


def walk_json_commands(obj, path="$"):
    """Yield (json_path, dict) for every dict that has a 'command' key (MCP servers, hooks)."""
    if isinstance(obj, dict):
        if "command" in obj and isinstance(obj["command"], str):
            yield path, obj
        for k, v in obj.items():
            yield from walk_json_commands(v, f"{path}.{k}")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            yield from walk_json_commands(v, f"{path}[{i}]")


def is_claude_config(relpath: str) -> bool:
    base = relpath.split("/")[-1]
    return (
        base == ".mcp.json"
        or relpath.startswith(".claude/") and base.endswith(".json")
        or relpath.startswith(EXTRAS_DIR + "/") and base.endswith(".json")
        or base == ".claude.json"
    )


def cmd_scan(args, staged: Path = None) -> dict:
    staged = staged or Path(args.staged).resolve()
    state = load_state(staged)
    direction = state["direction"]
    findings = [f for f in state["findings"] if f["category"] not in ("scan",)]
    to_mac = direction == "win2mac"
    log(f"Scanning {staged} ({direction})")

    crlf_files, lf_files = [], []
    lower_seen = {}
    abs_path_hits = 0
    for p in iter_files(staged):
        r = rel(p, staged)
        # --- filename problems
        lower = r.lower()
        if lower in lower_seen and lower_seen[lower] != r:
            findings.append(Finding("filenames", "manual", r,
                                    f"Filename differs only by case from '{lower_seen[lower]}'.",
                                    "Both macOS (default APFS) and Windows are case-insensitive: one of these will overwrite the other. Rename one.").to_dict())
        lower_seen.setdefault(lower, r)
        if not to_mac:
            for part in Path(r).parts:
                stem = part.split(".")[0].upper()
                if WINDOWS_ILLEGAL_CHARS.search(part) or part.rstrip() != part or part.rstrip(".") != part or stem in WINDOWS_RESERVED:
                    findings.append(Finding("filenames", "manual", r,
                                            f"Path component '{part}' is not a valid Windows filename.",
                                            "Rename it (convert will rename it automatically and record the change).").to_dict())
                    break
            if len(str(Path("C:/Users/name/Projects") / r)) > 240:
                findings.append(Finding("filenames", "info", r,
                                        "Path is long; may exceed Windows MAX_PATH (260) depending on where it's extracted.",
                                        "Enable long paths on Windows (git config core.longpaths true) or extract close to the drive root.").to_dict())

        if is_probably_binary(p):
            continue
        text = read_text(p)
        if text is None:
            continue

        # --- line endings
        if "\r\n" in text:
            crlf_files.append(r)
        elif "\n" in text:
            lf_files.append(r)

        # --- Claude / MCP configs
        if is_claude_config(r):
            try:
                data = load_json_loose(text)
            except Exception as e:  # noqa: BLE001
                findings.append(Finding("mcp", "manual", r, f"Could not parse JSON: {e}").to_dict())
                data = None
            if data is not None:
                for jpath, node in walk_json_commands(data):
                    cmdline = " ".join([node["command"]] + [str(a) for a in node.get("args", [])])
                    hits = scan_command_string(cmdline, direction)
                    is_hook = ".hooks" in jpath
                    if is_hook and hits:
                        findings.append(Finding("hooks", "manual", r,
                                                f"Hook at {jpath} uses source-OS shell syntax: {cmdline!r} ({'; '.join(hits)})",
                                                "Rewrite for the target shell (see references/<direction>.md, Hooks section).").to_dict())
                    elif not is_hook:
                        if to_mac and node["command"].lower() in ("cmd", "cmd.exe"):
                            findings.append(Finding("mcp", "info", r,
                                                    f"MCP server at {jpath} uses 'cmd /c' wrapper (auto-fixable).").to_dict())
                        elif not to_mac and node["command"] in NPM_CMD_SHIMS:
                            findings.append(Finding("mcp", "info", r,
                                                    f"MCP server at {jpath} runs '{node['command']}' directly; on Windows it needs 'cmd /c' (auto-fixable).").to_dict())
                        elif hits:
                            findings.append(Finding("mcp", "manual", r,
                                                    f"Command at {jpath}: {cmdline!r} ({'; '.join(hits)})",
                                                    "Adjust for target OS.").to_dict())
                    env = node.get("env") or {}
                    for k, v in env.items():
                        if isinstance(v, str) and (WIN_ABS_RE.search(v) or MAC_ABS_RE.search(v)):
                            findings.append(Finding("paths", "manual", r,
                                                    f"MCP env {k}={v!r} at {jpath} contains an absolute path.",
                                                    "Point it at the equivalent path on the target machine.").to_dict())
                # permission rules with absolute paths
                perms = data.get("permissions") if isinstance(data, dict) else None
                if isinstance(perms, dict):
                    for key in ("allow", "deny", "ask", "additionalDirectories"):
                        for rule in perms.get(key, []) or []:
                            if isinstance(rule, str) and (WIN_ABS_RE.search(rule) or MAC_ABS_RE.search(rule) or (to_mac and "\\" in rule)):
                                findings.append(Finding("permissions", "manual", r,
                                                        f"permissions.{key} rule {rule!r} contains an OS-specific path.",
                                                        "Use ~/ or a relative glob; forward slashes only.").to_dict())

        # --- package.json scripts
        if r.endswith("package.json"):
            try:
                data = load_json_loose(text)
                for name, script in (data.get("scripts") or {}).items():
                    hits = scan_command_string(script, direction)
                    if hits:
                        findings.append(Finding("npm-scripts", "manual", r,
                                                f"script \"{name}\": {script!r} ({'; '.join(hits)})",
                                                "Use cross-platform tools (cross-env, rimraf, shx, npm-run-all) or rewrite for the target shell.").to_dict())
            except Exception:  # noqa: BLE001
                pass

        # --- Makefile / task runners / CI
        base = Path(r).name
        if base in ("Makefile", "makefile", "Taskfile.yml", "Taskfile.yaml", "justfile", "Justfile") or r.startswith(".github/workflows/"):
            hits = scan_command_string(text, direction)
            if hits:
                findings.append(Finding("build-scripts", "manual", r,
                                        f"Contains source-OS shell syntax ({'; '.join(sorted(set(hits)))}).",
                                        "Review each recipe/step for the target shell.").to_dict())

        # --- VS Code launch/tasks
        if r.startswith(".vscode/") and base in ("launch.json", "tasks.json", "settings.json"):
            if (WIN_ABS_RE.search(text) or MAC_ABS_RE.search(text)
                    or ("windows" in text and to_mac) or ("osx" in text and not to_mac)):
                findings.append(Finding("editor-config", "manual", r,
                                        "Contains absolute paths or OS-specific blocks (\"windows\"/\"osx\").",
                                        "Add/adjust the target-OS block or use ${workspaceFolder}.").to_dict())

        # --- CLAUDE.md / AGENTS.md style instruction files
        if base.upper() in ("CLAUDE.MD", "AGENTS.MD", "CLAUDE.LOCAL.MD") or base.lower() == "claude.md":
            words = (["powershell", "pwsh", "cmd.exe", "git bash", "wsl", "windows", "%userprofile%", "c:\\"]
                     if to_mac else
                     ["zsh", "bash", "homebrew", "brew ", "macos", "mac os", "/users/", "chmod", "sudo", "~/library"])
            found = [w for w in words if w in text.lower()]
            if found:
                findings.append(Finding("claude-md", "manual", r,
                                        f"Mentions source-OS specifics: {', '.join(found)}.",
                                        "Claude follows CLAUDE.md literally; rewrite these instructions for the target OS.").to_dict())

        # --- OS-specific script files
        if to_mac and p.suffix.lower() in (".bat", ".cmd", ".ps1"):
            findings.append(Finding("scripts", "manual", r,
                                    "Windows-only script; will not run on macOS.",
                                    "Provide a .sh equivalent (see references/windows-to-macos.md) or drop it.").to_dict())
        if not to_mac and p.suffix.lower() in (".sh", ".bash", ".zsh"):
            findings.append(Finding("scripts", "info", r,
                                    "Shell script; runs on Windows only under Git Bash or WSL.",
                                    "Claude Code on Windows uses Git Bash, so this can still work; verify it has no mac-only commands (brew, open, etc.).").to_dict())

        # --- absolute paths anywhere in config/text
        if p.suffix.lower() in SCAN_TEXT_EXT or base.startswith(".env") or base in ("Dockerfile", "docker-compose.yml", "docker-compose.yaml", "compose.yml", "compose.yaml"):
            rx = WIN_ABS_RE if to_mac else MAC_ABS_RE
            for i, line in enumerate(text.splitlines(), 1):
                m = rx.search(line)
                if m and not line.lstrip().startswith(("#", "//")):
                    abs_path_hits += 1
                    if abs_path_hits <= 200:
                        in_src = state["source_posix"].lower() in m.group(1).replace("\\\\", "/").replace("\\", "/").lower()
                        findings.append(Finding("paths", "info" if in_src and state.get("dest_root") else "manual", r,
                                                f"Absolute path: {m.group(1)}", 
                                                "Inside the project root: rewritten automatically if --dest-root was given. Otherwise replace with the target path." if in_src
                                                else "Points outside the project; replace with the equivalent location on the target machine.",
                                                line=i).to_dict())

    # --- .gitattributes / autocrlf
    ga = staged / ".gitattributes"
    if not ga.exists() or "eol=" not in (read_text(ga) or ""):
        findings.append(Finding("line-endings", "info", ".gitattributes",
                                "No end-of-line policy defined (auto-fixable: convert adds one).").to_dict())
    gitcfg = staged / ".git" / "config"
    if gitcfg.exists() and "autocrlf = true" in (read_text(gitcfg) or ""):
        findings.append(Finding("line-endings", "manual", ".git/config",
                                "core.autocrlf=true is set in the repo config.",
                                "On the target run: git config core.autocrlf input (mac) or leave false (win) once .gitattributes is in place.").to_dict())
    if crlf_files:
        sev = "info" if to_mac else "info"
        findings.append(Finding("line-endings", sev, "(project)",
                                f"{len(crlf_files)} text file(s) use CRLF, {len(lf_files)} use LF." +
                                (" convert will normalise CRLF -> LF." if to_mac else " Mixed endings; convert normalises to LF except .bat/.cmd/.ps1."),
                                ).to_dict())
    sh_crlf = [f for f in crlf_files if f.endswith((".sh", ".bash", ".zsh")) or has_shebang(staged / f)]
    for f in sh_crlf:
        findings.append(Finding("line-endings", "info", f,
                                "Script has CRLF endings (would fail with 'bad interpreter'); auto-fixed by convert.").to_dict())

    # --- dependency / toolchain hints (info)
    hints = []
    for marker, hint in [
        ("package-lock.json", "Node: run `npm ci`"), ("yarn.lock", "Node: run `yarn install`"),
        ("pnpm-lock.yaml", "Node: run `pnpm install`"), ("bun.lockb", "Node: run `bun install`"),
        ("requirements.txt", "Python: create a fresh venv and `pip install -r requirements.txt`"),
        ("pyproject.toml", "Python: `uv sync` / `poetry install` / `pip install -e .`"),
        ("Pipfile", "Python: `pipenv install`"), ("Cargo.toml", "Rust: `cargo build`"),
        ("go.mod", "Go: `go mod download`"), ("Gemfile", "Ruby: `bundle install`"),
        ("composer.json", "PHP: `composer install`"), ("Dockerfile", "Docker: rebuild images on the target"),
    ]:
        if (staged / marker).exists():
            hints.append(hint)
    for f in list(staged.glob("*.csproj")) + list(staged.glob("*.sln")):
        hints.append(f".NET: `dotnet restore` ({f.name})")
    nvmrc = staged / ".nvmrc"
    if nvmrc.exists():
        hints.append(f"Node version pinned in .nvmrc: {read_text(nvmrc).strip()} (use nvm/fnm on the target)")
    state["toolchain_hints"] = hints

    state["findings"] = findings
    state["crlf_count"] = len(crlf_files)
    state["lf_count"] = len(lf_files)
    state["steps_done"].append("scan")
    save_state(staged, state)
    write_report(staged, state)
    summarize(state)
    return state


# --------------------------------------------------------------------------- convert

def path_variants(p: str):
    """All the spellings an absolute path might have inside text/JSON files."""
    posix = p.replace("\\", "/")
    win = posix.replace("/", "\\")
    variants = {posix, win, win.replace("\\", "\\\\")}
    # file URIs
    variants.add("file:///" + posix.lstrip("/"))
    return [v for v in variants if v]


def sanitize_windows_name(name: str) -> str:
    new = WINDOWS_ILLEGAL_CHARS.sub("_", name).rstrip(" .")
    stem = new.split(".")[0].upper()
    if stem in WINDOWS_RESERVED:
        new = "_" + new
    return new or "_"


def cmd_convert(args, staged: Path = None) -> dict:
    staged = staged or Path(args.staged).resolve()
    state = load_state(staged)
    direction = state["direction"]
    to_mac = direction == "win2mac"
    dest_root = args.dest_root or state.get("dest_root")
    state["dest_root"] = dest_root
    findings = state["findings"]
    fixed = 0
    log(f"Converting {staged} ({direction})")

    # 1. Rename invalid Windows filenames (mac2win), deepest first.
    if not to_mac:
        entries = sorted((p for p in staged.rglob("*") if ".git" not in p.parts),
                         key=lambda p: len(p.parts), reverse=True)
        for p in entries:
            new_name = sanitize_windows_name(p.name)
            if new_name != p.name:
                target = p.with_name(new_name)
                i = 1
                while target.exists():
                    target = p.with_name(f"{Path(new_name).stem}_{i}{Path(new_name).suffix}")
                    i += 1
                p.rename(target)
                fixed += 1
                findings.append(Finding("filenames", "fixed", rel(p, staged),
                                        f"Renamed to '{target.name}' (invalid on Windows).",
                                        "Update any references to the old name in code/config.").to_dict())

    # 2. Per-file text transforms
    src_variants = path_variants(state["source_posix"]) if dest_root else []
    if dest_root:
        dest_norm = dest_root.replace("\\", "/").rstrip("/")
        if not to_mac and not re.match(r"^[A-Za-z]:/", dest_norm):
            log("WARNING: --dest-root for Windows should look like C:/Users/you/Projects/name")
        # For Windows targets we write forward slashes: valid for node, python, git, VS Code, Claude Code.
        dest_for_text = dest_norm
        dest_for_json = dest_norm  # forward slashes need no escaping
    rewritten_paths = 0
    eol_fixed = 0

    for p in iter_files(staged):
        r = rel(p, staged)
        if is_probably_binary(p):
            continue
        raw = p.read_bytes()
        try:
            text = raw.decode("utf-8")
            enc = "utf-8"
        except UnicodeDecodeError:
            continue  # leave non-utf8 text alone
        original = text
        suffix = p.suffix.lower()

        # 2a. absolute project-root path rewriting
        if src_variants:
            for v in sorted(src_variants, key=len, reverse=True):
                if v in text:
                    n = text.count(v)
                    text = text.replace(v, dest_for_text)
                    rewritten_paths += n
                    findings.append(Finding("paths", "fixed", r,
                                            f"Replaced {n} occurrence(s) of the old project root with {dest_for_text}").to_dict())
                # case-insensitive match on Windows sources
                elif to_mac and v.lower() in text.lower():
                    rx = re.compile(re.escape(v), re.I)
                    text, n = rx.subn(dest_for_text.replace("\\", "\\\\"), text)
                    if n:
                        rewritten_paths += n
                        findings.append(Finding("paths", "fixed", r,
                                                f"Replaced {n} occurrence(s) of the old project root (case-insensitive) with {dest_for_text}").to_dict())

            # tails of rewritten paths still carry the source separators: fix them
            if to_mac and dest_for_text in text:
                tail_rx = re.compile(re.escape(dest_for_text) + r'((?:\\\\|\\)[^\s"\'<>|,;)\]]*)')
                text = tail_rx.sub(lambda m: dest_for_text + m.group(1).replace("\\\\", "/").replace("\\", "/"), text)

        # 2b. MCP / Claude config JSON transforms
        if is_claude_config(r):
            try:
                data = load_json_loose(text)
                changed = False
                for jpath, node in walk_json_commands(data):
                    if ".hooks" in jpath:
                        continue
                    cmd = node["command"]
                    args_list = list(node.get("args") or [])
                    if to_mac:
                        if cmd.lower() in ("cmd", "cmd.exe") and args_list and args_list[0].lower() in ("/c", "/k"):
                            node["command"] = args_list[1] if len(args_list) > 1 else ""
                            node["args"] = args_list[2:]
                            changed = True
                            findings.append(Finding("mcp", "fixed", r,
                                                    f"{jpath}: removed 'cmd /c' wrapper -> {node['command']} {' '.join(node['args'])}").to_dict())
                        for ext in (".cmd", ".exe", ".bat"):
                            if node["command"].lower().endswith(ext):
                                node["command"] = node["command"][: -len(ext)]
                                changed = True
                                findings.append(Finding("mcp", "fixed", r, f"{jpath}: stripped '{ext}' from command").to_dict())
                        if node["command"] == "python":
                            node["command"] = "python3"
                            changed = True
                            findings.append(Finding("mcp", "fixed", r, f"{jpath}: python -> python3").to_dict())
                        if "\\" in node["command"]:
                            node["command"] = node["command"].replace("\\", "/")
                            changed = True
                        node["args"] = [a.replace("\\", "/") if isinstance(a, str) and re.search(r"\\[A-Za-z0-9_.]", a) else a
                                        for a in node.get("args", [])]
                    else:
                        if cmd in NPM_CMD_SHIMS:
                            node["command"] = "cmd"
                            node["args"] = ["/c", cmd] + args_list
                            changed = True
                            findings.append(Finding("mcp", "fixed", r,
                                                    f"{jpath}: wrapped '{cmd}' in 'cmd /c' (required for npm shims on Windows)").to_dict())
                        if cmd == "python3":
                            node["command"] = "python"
                            changed = True
                            findings.append(Finding("mcp", "fixed", r, f"{jpath}: python3 -> python").to_dict())
                if changed:
                    text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
                    findings.append(Finding("mcp", "info", r,
                                            "File was re-serialised with 2-space indent; comments (if any) were dropped.").to_dict())
            except Exception as e:  # noqa: BLE001
                findings.append(Finding("mcp", "manual", r, f"Could not auto-convert JSON: {e}").to_dict())

        # 2c. line endings
        if suffix in CRLF_ON_WINDOWS_EXT:
            want_crlf = True
        else:
            want_crlf = False   # LF everywhere else, on both OSes
        norm = text.replace("\r\n", "\n").replace("\r", "\n")
        new_text = norm.replace("\n", "\r\n") if want_crlf else norm
        if new_text != text and ("\r\n" in text or want_crlf):
            eol_fixed += 1
            text = new_text

        if text != original:
            p.write_bytes(text.encode(enc))
            fixed += 1

    if eol_fixed:
        findings.append(Finding("line-endings", "fixed", "(project)",
                                f"Normalised line endings in {eol_fixed} file(s): LF everywhere, CRLF for .bat/.cmd/.ps1.").to_dict())
    if rewritten_paths:
        state["paths_rewritten"] = rewritten_paths

    # 3. .gitattributes
    ga = staged / ".gitattributes"
    block = ("\n# Added by OSmigration: keep line endings deterministic across Windows and macOS\n"
             "* text=auto eol=lf\n*.bat text eol=crlf\n*.cmd text eol=crlf\n*.ps1 text eol=crlf\n")
    existing = read_text(ga) if ga.exists() else ""
    if "eol=" not in (existing or ""):
        ga.write_text((existing or "").rstrip("\n") + ("\n" if existing else "") + block.lstrip("\n"), encoding="utf-8")
        fixed += 1
        findings.append(Finding("line-endings", "fixed", ".gitattributes",
                                "Added end-of-line policy (LF, except Windows batch/PowerShell files).").to_dict())

    # 4. Executable bits (stored in the zip; matters for win2mac)
    exec_files = []
    for p in iter_files(staged):
        if p.suffix.lower() in (".sh", ".bash", ".zsh") or (not is_probably_binary(p) and has_shebang(p)):
            exec_files.append(rel(p, staged))
            try:
                if os.name != "nt":
                    p.chmod(p.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
            except OSError:
                pass
    state["exec_files"] = exec_files
    if exec_files and to_mac:
        findings.append(Finding("permissions", "fixed", "(project)",
                                f"{len(exec_files)} script(s) will be marked executable in the archive.",
                                "If you extract with a tool that ignores unix permissions, run: chmod +x on them (list in report).").to_dict())

    # drop the scan-time "info" notes that convert has now resolved
    resolved_notes = {"(auto-fixable)", "auto-fixed by convert", "auto-fixable: convert adds one", "convert will normalise", "convert normalises"}
    findings = [f for f in findings if not (f["severity"] == "info" and any(k in f["detail"] for k in resolved_notes))]
    # filenames renamed above no longer need a manual note
    findings = [f for f in findings if not (f["category"] == "filenames" and f["severity"] == "manual"
                                            and "not a valid Windows filename" in f["detail"])]
    # a project-root path that was rewritten no longer needs a manual note
    if rewritten_paths:
        findings = [f for f in findings if not (f["category"] == "paths" and f["severity"] in ("info", "manual")
                                                and "Inside the project root" in (f.get("suggestion") or ""))]
    state["findings"] = findings
    state["steps_done"].append("convert")
    save_state(staged, state)
    write_report(staged, state)
    log(f"Convert done: {fixed} file(s) changed in the staged copy.")
    summarize(state)
    return state


# --------------------------------------------------------------------------- package

def cmd_package(args, staged: Path = None) -> Path:
    staged = staged or Path(args.staged).resolve()
    state = load_state(staged)
    workdir = Path(args.workdir or os.getcwd()).resolve()
    workdir.mkdir(parents=True, exist_ok=True)
    name = f"{state['project_name']}_to-transfer.zip"
    out = workdir / name
    if out.exists():
        log(f"Note: overwriting existing {out}")
    exec_set = set(state.get("exec_files", []))
    write_report(staged, state)   # make sure the report inside the archive is current

    log(f"Packaging -> {out}")
    count = 0
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for root, dirs, files in os.walk(staged):
            r = Path(root)
            for d in dirs:
                dp = r / d
                if dp.is_symlink():
                    add_symlink(zf, dp, f"{state['project_name']}/{rel(dp, staged)}")
            for f in files:
                fp = r / f
                if f == STATE_FILE:
                    continue
                arc = f"{state['project_name']}/{rel(fp, staged)}"
                if fp.is_symlink():
                    add_symlink(zf, fp, arc)
                    continue
                zi = zipfile.ZipInfo.from_file(fp, arc)
                zi.compress_type = zipfile.ZIP_DEFLATED
                mode = fp.stat().st_mode & 0o7777 or 0o644
                if rel(fp, staged) in exec_set:
                    mode |= 0o111
                zi.external_attr = (stat.S_IFREG | mode) << 16
                with open(fp, "rb") as fh:
                    zf.writestr(zi, fh.read())
                count += 1
    # copy the report next to the archive too
    shutil.copy2(staged / REPORT_MD, workdir / f"{state['project_name']}_MIGRATION_REPORT.md")
    size_mb = out.stat().st_size / (1024 * 1024)
    log(f"Archive written: {out} ({count} files, {size_mb:.1f} MB)")
    log(f"Report copied to: {workdir / (state['project_name'] + '_MIGRATION_REPORT.md')}")
    log(f"ARCHIVE={out}")
    if not args.keep_staging:
        shutil.rmtree(staged.parent, ignore_errors=True)
        log("Staging directory removed.")
    else:
        log(f"Staging directory kept at {staged}")
    return out


def add_symlink(zf: zipfile.ZipFile, path: Path, arcname: str):
    target = os.readlink(path)
    zi = zipfile.ZipInfo(arcname)
    zi.create_system = 3
    zi.external_attr = (stat.S_IFLNK | 0o777) << 16
    zf.writestr(zi, target)


# --------------------------------------------------------------------------- report

def summarize(state: dict):
    f = state["findings"]
    n_fixed = sum(1 for x in f if x["severity"] == "fixed")
    n_manual = sum(1 for x in f if x["severity"] == "manual")
    n_info = sum(1 for x in f if x["severity"] == "info")
    log(f"Findings: {n_fixed} auto-fixed, {n_manual} need manual action, {n_info} informational.")
    log(f"REPORT={Path(state['staged']) / REPORT_MD}")


def write_report(staged: Path, state: dict):
    f = state["findings"]
    to_mac = state["direction"] == "win2mac"
    target = "macOS" if to_mac else "Windows"
    src_os = "Windows" if to_mac else "macOS"
    groups = {"fixed": [], "manual": [], "info": []}
    for x in f:
        groups.get(x["severity"], groups["info"]).append(x)

    def fmt(x):
        loc = x["file"] + (f":{x['line']}" if x.get("line") else "")
        s = f"- `{loc}` — {x['detail']}"
        if x.get("suggestion"):
            s += f"\n  - _{x['suggestion']}_"
        return s

    lines = [
        f"# Migration report: {state['project_name']} ({src_os} → {target})",
        "",
        f"- Source (untouched): `{state['source']}`",
        f"- Staged copy: `{state['staged']}`",
        f"- Direction: `{state['direction']}`",
        f"- Target project root: `{state.get('dest_root') or '(not specified: absolute paths must be fixed by hand)'}`",
        f"- Generated: {_dt.datetime.now().strftime('%Y-%m-%d %H:%M')} by OSmigration {VERSION}",
        f"- Steps completed: {', '.join(state['steps_done'])}",
        "",
        "## Skipped (regenerate on the target, do not copy)",
        "",
    ]
    lines += [f"- `{d}/`" for d in state.get("skipped_dirs", [])] or ["- (none found)"]
    lines += ["", f"## Automatic changes applied to the staged copy ({len(groups['fixed'])})", ""]
    lines += [fmt(x) for x in groups["fixed"]] or ["- (none yet: run `convert`)"]
    lines += ["", f"## Manual actions required ({len(groups['manual'])})", "",
              "These cannot be fixed safely by a script. Edit them in the staged copy before packaging, "
              "or on the target machine after extracting.", ""]
    lines += [f"{i}. {fmt(x)[2:]}" for i, x in enumerate(groups["manual"], 1)] or ["- (none detected)"]
    lines += ["", f"## Notes ({len(groups['info'])})", ""]
    lines += [fmt(x) for x in groups["info"]] or ["- (none)"]

    if state.get("exec_files"):
        lines += ["", "## Executable scripts (marked +x in the archive)", ""]
        lines += [f"- `{e}`" for e in state["exec_files"]]
    if state.get("global_extras"):
        lines += ["", "## User-level Claude Code extras included", "",
                  f"Found in `{EXTRAS_DIR}/` with its own README: " + ", ".join(state["global_extras"])]

    lines += ["", f"## Checklist on the {target} machine", ""]
    if to_mac:
        steps = [
            "Unzip: `unzip <project>_to-transfer.zip -d ~/Projects` (Finder double-click also works)",
            "Install a Node version manager (`fnm` or `nvm`) and the Node version the project uses (`.nvmrc` if present)",
            "Reinstall dependencies: " + "; ".join(state.get("toolchain_hints") or ["see your package manager"]),
            "`git config core.autocrlf input` inside the repo (the new `.gitattributes` keeps LF)",
            "If any script won't run: `chmod +x path/to/script.sh`",
            "Install Claude Code (`npm install -g @anthropic-ai/claude-code` or `brew install claude-code`) and run `claude` to log in (credentials are never transferred)",
            "Restore user-level extras from `_claude-global-extras/` if included (see its README); re-add MCP servers with `claude mcp add-json`",
            "Move any environment variables from your PowerShell profile into `~/.zshrc` (`export VAR=value`)",
            "Work through the *Manual actions* above, then run `claude` in the project and `/doctor`",
        ]
    else:
        steps = [
            "Unzip with Explorer or `Expand-Archive .\\<project>_to-transfer.zip -DestinationPath C:\\Users\\you\\Projects`",
            "Install Git for Windows (Claude Code uses Git Bash) and a Node version manager (`fnm` or `nvm-windows`)",
            "Reinstall dependencies: " + "; ".join(state.get("toolchain_hints") or ["see your package manager"]),
            "`git config core.autocrlf false` inside the repo (the new `.gitattributes` enforces LF; do not let Git convert to CRLF)",
            "Enable long paths if needed: `git config core.longpaths true`",
            "Install Claude Code (`npm install -g @anthropic-ai/claude-code` or `winget install Anthropic.ClaudeCode`) and run `claude` to log in",
            "Restore user-level extras from `_claude-global-extras/` if included (see its README); re-add MCP servers with `claude mcp add-json`",
            "Move environment variables from `~/.zshrc` into User Environment Variables (or `$PROFILE` for PowerShell)",
            "Work through the *Manual actions* above, then run `claude` in the project and `/doctor`",
        ]
    lines += [f"{i}. {s}" for i, s in enumerate(steps, 1)]
    lines.append("")
    (staged / REPORT_MD).write_text("\n".join(lines), encoding="utf-8")


# --------------------------------------------------------------------------- cli

def build_parser():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    def add_stage_args(sp):
        sp.add_argument("source", help="path to the project on this machine (never modified)")
        sp.add_argument("--direction", required=True, choices=["win2mac", "mac2win"],
                        help="win2mac: Windows -> macOS, mac2win: macOS -> Windows")
        sp.add_argument("--dest-root", help="where the project will live on the target, e.g. /Users/user-name/Projects/myapp or C:/Users/user-name/Projects/myapp. Enables automatic rewriting of absolute paths.")
        sp.add_argument("--name", help="project name for the archive (default: folder name)")
        sp.add_argument("--source-root", help="how the project root is spelled inside its own files if different from the real path (e.g. a mapped drive or junction)")
        sp.add_argument("--exclude", action="append", metavar="DIR", help="extra directory name to skip (repeatable)")
        sp.add_argument("--keep", action="append", metavar="DIR", help="directory name to keep even if normally excluded (repeatable)")
        sp.add_argument("--exclude-git", action="store_true", help="do not copy the .git directory")
        sp.add_argument("--include-global", action="store_true",
                        help="also collect user-level Claude Code config (~/.claude/CLAUDE.md, commands, agents, MCP servers) into _claude-global-extras/")

    def add_staged_arg(sp):
        sp.add_argument("--staged", required=True, help="staging directory printed by 'stage'/'prepare'")

    sp = sub.add_parser("stage", help="copy project to a temp staging dir")
    add_stage_args(sp)
    sp = sub.add_parser("scan", help="detect OS-specific content in the staged copy")
    add_staged_arg(sp)
    sp = sub.add_parser("convert", help="apply automatic fixes in the staged copy")
    add_staged_arg(sp)
    sp.add_argument("--dest-root")
    sp = sub.add_parser("package", help="zip the staged copy into <workdir>/<project>_to-transfer.zip")
    add_staged_arg(sp)
    sp.add_argument("--workdir", help="where to write the archive (default: current directory)")
    sp.add_argument("--keep-staging", action="store_true", help="do not delete the temp staging dir afterwards")
    for name, help_ in (("prepare", "stage + scan + convert, then stop for manual review"),
                        ("all", "stage + scan + convert + package in one go")):
        sp = sub.add_parser(name, help=help_)
        add_stage_args(sp)
        sp.add_argument("--workdir")
        sp.add_argument("--keep-staging", action="store_true")
    return p


def main(argv=None):
    args = build_parser().parse_args(argv)
    if args.cmd == "stage":
        cmd_stage(args)
    elif args.cmd == "scan":
        cmd_scan(args)
    elif args.cmd == "convert":
        cmd_convert(args)
    elif args.cmd == "package":
        cmd_package(args)
    elif args.cmd in ("prepare", "all"):
        staged = cmd_stage(args)
        cmd_scan(args, staged)
        cmd_convert(args, staged)
        if args.cmd == "all":
            cmd_package(args, staged)
        else:
            log("\nStaged copy is ready for manual edits. When done:")
            log(f"  python {Path(__file__).name} package --staged \"{staged}\"")


if __name__ == "__main__":
    main()
